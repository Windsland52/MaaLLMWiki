"""Upstream MaaFramework commits, filed under the first registered release that contains them.

For each pair of consecutive registered releases, every non-merge commit reachable from the newer
release and not from the older one is recorded with its subject line, pull-request number and
changed paths. Commits whose subject ends with ``[skip changelog]`` (automated formatting and
submodule updates) are left out, as the upstream changelog leaves them out. Commits up to the first
registered release are not listed.
"""

from __future__ import annotations

import re
import subprocess
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

from .models import ReleaseRecord, UpstreamCommit, UpstreamCommitCatalog
from .validation import load_release_catalog

PATH_LIMIT = 20
SUBJECT_LIMIT = 300
SKIP_MARKER = "[skip changelog]"
_PAGE_PATH_LIMIT = 5
_PULL_REQUEST = re.compile(r"\(#(?P<number>\d+)\)\s*$")
_GENERATOR = "maa-wiki-sync-maafw-history"


def _log(repository: Path, previous: ReleaseRecord, release: ReleaseRecord) -> bytes:
    return subprocess.run(
        [
            "git",
            "-c",
            "core.quotepath=false",
            "log",
            "--no-merges",
            "--no-renames",
            "--reverse",
            "--topo-order",
            "-z",
            "--format=%H%x1f%s",
            "--name-only",
            f"{previous.commit}..{release.commit}",
        ],
        cwd=repository,
        check=True,
        capture_output=True,
    ).stdout


def parse_log(output: bytes) -> list[tuple[str, str, list[str]]]:
    """Split ``git log -z --format=%H%x1f%s --name-only`` output into (sha, subject, paths)."""
    entries: list[tuple[str, str, list[str]]] = []
    for raw in output.decode("utf-8", "replace").split("\0"):
        token = raw.lstrip("\n")
        if not token:
            continue
        if "\x1f" in token:
            sha, _, subject = token.partition("\x1f")
            entries.append((sha, subject.strip(), []))
        elif entries:
            entries[-1][2].append(token)
    return entries


def _commit(version: str, sha: str, subject: str, paths: list[str]) -> UpstreamCommit:
    match = _PULL_REQUEST.search(subject)
    ordered = sorted(set(paths))
    return UpstreamCommit(
        version=version,
        commit=sha,
        subject=subject[:SUBJECT_LIMIT] or sha,
        pull_request=int(match["number"]) if match is not None else None,
        path_count=len(ordered),
        paths=ordered[:PATH_LIMIT],
    )


def build_upstream_commits(root: Path, repository: Path) -> UpstreamCommitCatalog:
    """Record the upstream commits between every pair of consecutive registered releases."""
    releases = load_release_catalog(root).releases
    commits: list[UpstreamCommit] = []
    for previous, release in zip(releases, releases[1:], strict=False):
        for sha, subject, paths in parse_log(_log(repository, previous, release)):
            if subject.endswith(SKIP_MARKER):
                continue
            commits.append(_commit(release.version, sha, subject, paths))
    return UpstreamCommitCatalog(source_id="maafw", commits=commits)


def _version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def render_upstream_commits_page(
    catalog: UpstreamCommitCatalog,
    releases: list[ReleaseRecord],
    repository_url: str,
) -> str:
    """Render the commit index, newest release first, commits in upstream order."""
    base_url = repository_url.rstrip("/")
    by_version: defaultdict[str, list[UpstreamCommit]] = defaultdict(list)
    for commit in catalog.commits:
        by_version[commit.version].append(commit)
    previous_tag = {
        release.version: earlier.tag
        for earlier, release in zip(releases, releases[1:], strict=False)
    }
    tags = {release.version: release.tag for release in releases}
    lines = [
        f"<!-- Generated by {_GENERATOR}. Do not edit manually. -->",
        "# Upstream commits",
        "",
        "Every upstream non-merge commit, filed under the first registered release that contains "
        "it: the commits between the previous registered release and that release. Use this page "
        "to find the change behind a behaviour difference that no declared API element shows, "
        "then read the commit's diff. Subjects are upstream text; a subject states intent, not "
        "verified behaviour.",
        "",
        f"Commits whose subject ends with `{SKIP_MARKER}` (automated formatting and submodule "
        "updates) are left out, as the upstream changelog leaves them out. Commits up to the "
        f"first registered release (`{releases[0].version}`) are not listed. Each commit lists "
        f"up to {PATH_LIMIT} changed paths in the source YAML and {_PAGE_PATH_LIMIT} here.",
        "",
        "[← Version index](./index.md) · [Machine changes](./machine-changes.md) · "
        "[Symbols](./machine-symbols.md)",
        "",
        "Source of truth: `sources/maa-framework/upstream-commits.yaml` "
        f"({len(catalog.commits)} commits over {len(by_version)} releases).",
        "",
    ]
    for version in sorted(by_version, key=_version_key, reverse=True):
        group = by_version[version]
        heading = f"## [{version}](./{version}/index.md)"
        lines.extend([heading, ""])
        earlier = previous_tag.get(version)
        tag = tags.get(version)
        if earlier is not None and tag is not None:
            lines.extend(
                [
                    f"{len(group)} commits since `{earlier}` · "
                    f"[compare]({base_url}/compare/{quote(earlier)}...{quote(tag)})",
                    "",
                ]
            )
        for commit in group:
            subject = commit.subject
            match = _PULL_REQUEST.search(subject)
            if match is not None:
                number = match["number"]
                subject = f"{subject[: match.start()]}([#{number}]({base_url}/pull/{number}))"
            line = f"- [`{commit.commit[:10]}`]({base_url}/commit/{commit.commit}) {subject}"
            if commit.paths:
                shown = ", ".join(f"`{path}`" for path in commit.paths[:_PAGE_PATH_LIMIT])
                hidden = commit.path_count - min(commit.path_count, _PAGE_PATH_LIMIT)
                line += f" — {shown}" + (f" and {hidden} more" if hidden else "")
            lines.append(line)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
