from __future__ import annotations

from urllib.parse import quote

from .models import ReleaseCatalog, SemanticChangeCatalog, SourceMap

_GENERATOR = "maa-wiki-sync-maafw"
_MISSING_RELEASE = "unregistered"


def _pinned_link(repository_url: str, revision: str, path: str) -> str:
    url = f"{repository_url.rstrip('/')}/blob/{revision}/{quote(path, safe='/')}"
    return f"[`{path}`]({url})"


def _label_paths(repository_url: str, revision: str, paths: list[str]) -> str:
    return ", ".join(_pinned_link(repository_url, revision, path) for path in paths)


def render_topics_page(
    *,
    source_map: SourceMap,
    repository_url: str,
    latest_release: str,
) -> str:
    """Render the curated routing topics as navigation, one section per topic."""
    lines = [
        f"<!-- Generated by {_GENERATOR}. Do not edit manually. -->",
        "# Topic routes",
        "",
        "Hand-authored routing: a topic maps to the files, symbols, and literal search terms that",
        "answer it. Each variant applies to one release and proves only that the listed targets",
        f"existed at that pinned commit. Latest indexed release: `{latest_release}`.",
        "",
        "Source of truth: `sources/maa-framework/source-map.yaml`.",
        "",
    ]
    for topic in source_map.topics:
        lines.extend([f"## {topic.id}", "", f"Source: `{topic.source_id}`.", ""])
        for variant in topic.variants:
            lines.extend([f"- Applies to `{variant.applies_to}` at `{variant.revision}`"])
            files = _label_paths(repository_url, variant.revision, variant.paths)
            lines.append(f"  - Files: {files}")
            if variant.symbols:
                symbols = ", ".join(f"`{symbol}`" for symbol in variant.symbols)
                lines.append(f"  - Symbols: {symbols}")
            terms = ", ".join(f"`{term}`" for term in variant.terms)
            lines.append(f"  - Terms: {terms}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_semantic_changes_page(
    *,
    source_id: str,
    semantic_changes: SemanticChangeCatalog,
    source_map: SourceMap,
    releases: ReleaseCatalog,
    repository_url: str,
) -> str:
    """Render the recorded behaviour changes, grouped by the release that first carried them."""
    release_commits = {release.version: release.commit for release in releases.releases}
    topics = {topic.id: topic for topic in source_map.topics}
    changes = [change for change in semantic_changes.changes if change.paths]
    grouped: dict[str, list[str]] = {}
    for change in changes:
        topic = topics.get(change.topic_id)
        lines = [f"- `{change.topic_id}` at `{change.revision}`: {change.description}"]
        if topic is not None:
            lines.append(
                f"  - Route: {_label_paths(repository_url, change.revision, change.paths)}"
            )
        else:
            files = _label_paths(repository_url, change.revision, change.paths)
            lines.append(f"  - Files: {files}")
        grouped.setdefault(change.first_version, []).extend(lines)

    ordered = sorted(grouped, key=lambda version: tuple(int(part) for part in version.split(".")))
    lines = [
        f"<!-- Generated by {_GENERATOR}. Do not edit manually. -->",
        "# Behaviour changes",
        "",
        "Recorded cross-version behaviour changes: what changed, which release first carried it,",
        "and where to read the pinned source. One entry per reviewed change, not one per release,",
        "so a release with no entry is not evidence that nothing changed.",
        "",
        f"Source of truth: `sources/maa-framework/semantic-changes.yaml` (source `{source_id}`;",
        f"{len(semantic_changes.changes)} entries over {len(ordered)} releases).",
        "",
    ]
    for version in ordered:
        commit = release_commits.get(version, _MISSING_RELEASE)
        lines.extend([f"## {version}", "", f"Revision: `{commit}`", ""])
        lines.extend(grouped[version])
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
